function hit(wall, op) {
  const [x0, y0, x1, y1] = wall;
  const [a, b, c, d] = op;
  const ix0 = Math.max(x0, a - 0.08);
  const ix1 = Math.min(x1, c + 0.08);
  const iy0 = Math.max(y0, b - 0.08);
  const iy1 = Math.min(y1, d + 0.08);
  return ix1 - ix0 > 0.04 && iy1 - iy0 > 0.04;
}

