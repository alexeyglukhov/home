        span(h.a, h.b, PLINTH, h.z0);
        span(h.a, h.b, h.z1, zTop);
        const color = h.kind === "p" ? FRAME_W : h.kind === "d" || h.kind === "i" ? 0x6b3e24 : FRAME_Y;
