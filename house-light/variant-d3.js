const PLINTH = 0.40;
const FLOOR = PLINTH + 0.04;
// Чердачное перекрытие жилого дома: Rт.норм = 6,0 м²·°С/Вт
// (ТКП 45-2.04-43-2006, совмещённые покрытия и чердачные перекрытия).
// Минвата λА = 0,042 Вт/(м·°С) → 250 мм, R = 5,95; с подшивкой и настилом выше 6,0.
const LINING = 0.0125;
const INSUL = 0.25;
const DECK = 0.025;
const CEIL_BOT = FLOOR + 3.20;
const CEIL_TOP = CEIL_BOT + LINING + INSUL + DECK;
const MAUERLAT = 0.15;
const WALL_TOP = CEIL_TOP + MAUERLAT;
const HEAD = 2.45;
const YELL_SILL = 1.10;
const PAN_SILL = PLINTH + 0.10;
const WALL_C = 0xd9d3c8;
const FRAME_Y = 0xe0b83a;
const FRAME_W = 0xf7f6f2;
