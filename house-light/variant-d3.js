    emit(bottomL, roofL, roofR);
    emit(bottomL, roofR, bottomR);
    emit(roofL, L0, R0);
    emit(roofL, R0, roofR);
    emit(L0, L1, [uLo, zWinTop]);
    emit(L0, [uLo, zWinTop], [uLo, zWinBot]);
    emit([uHi, zWinBot], [uHi, zWinTop], R1);
    emit([uHi, zWinBot], R1, R0);
    emit(L1, peak, R1);
