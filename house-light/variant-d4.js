  gableWithWindow(
    toEast,
    [yNWall, WALL_TOP], [yNWall, zNorth(yNWall)], [cy, Zr], [ySWall, zWing(ySWall)], [ySWall, WALL_TOP],
    cy + halfWin, cy - halfWin,
    [1, 0, 0]
  );
